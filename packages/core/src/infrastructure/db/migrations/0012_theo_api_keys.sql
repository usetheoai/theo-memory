CREATE TABLE IF NOT EXISTS "theo_api_keys" (
	"id" varchar(20) PRIMARY KEY NOT NULL,
	"subject" text NOT NULL,
	"tenant_id" text DEFAULT 'self' NOT NULL,
	"key_name" varchar(64) NOT NULL,
	"key_hash" varchar(64) NOT NULL,
	"key_prefix" varchar(12) NOT NULL,
	"scopes" jsonb NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"last_used_at" timestamp with time zone,
	"expires_at" timestamp with time zone,
	"revoked_at" timestamp with time zone,
	"rotated_from" varchar(20),
	CONSTRAINT "theo_api_keys_key_hash_unique" UNIQUE("key_hash"),
	CONSTRAINT "theo_api_keys_no_self_rotation" CHECK (id != rotated_from)
);
